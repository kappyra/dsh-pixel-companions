#!/usr/bin/env node
/**
 * Build `client.js`, the browser half the Harness module loader serves.
 *
 * The Harness loads a plugin bundle through `window.__ModuleLoader__.load({ id,
 * factory })`; the factory's `require` resolves `react` from the page's shared
 * module table, so React is never bundled. The compiled module is wrapped in
 * that registration here.
 *
 * The generated `client.js` is committed: a Git/tarball install runs no build.
 *
 * Usage: node tools/build-client.mjs [--check]
 *   --check  build in memory and validate, write nothing (CI)
 */
import { execFileSync } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const PACKAGE = JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8')).name
const ENTRY = join(ROOT, 'src', 'client', 'index.ts')
const TARGET = join(ROOT, 'client.js')
const checkOnly = process.argv.includes('--check')

let esbuild
try {
  esbuild = await import('esbuild')
} catch {
  console.error('error: esbuild is not installed. Run `npm install` first.')
  process.exit(1)
}

const result = await esbuild.build({
  entryPoints: [ENTRY],
  bundle: true,
  write: false,
  format: 'cjs',
  platform: 'browser',
  target: 'es2022',
  jsx: 'transform',
  // React must come from the page's module table, never from this bundle.
  external: ['react'],
  legalComments: 'none',
  logLevel: 'warning',
  define: { 'process.env.NODE_ENV': '"production"' },
})

const compiled = result.outputFiles[0].text
const registration = [
  `/* Generated by tools/build-client.mjs from src/client/index.ts. Do not edit. */`,
  `window.__ModuleLoader__.load({`,
  `  id: ${JSON.stringify(PACKAGE)},`,
  `  factory(require) {`,
  `    const module = { exports: {} };`,
  `    const exports = module.exports;`,
  compiled,
  `    return module.exports;`,
  `  },`,
  `});`,
  ``,
].join('\n')

if (checkOnly) {
  console.log(`checked ${PACKAGE}: ${(Buffer.byteLength(registration) / 1024).toFixed(0)} KiB`)
  process.exit(0)
}

writeFileSync(TARGET, registration)
// The generated file is a plain script served to the browser; check it parses.
execFileSync(process.execPath, ['--check', TARGET], { stdio: 'inherit' })
console.log(`wrote client.js (${(Buffer.byteLength(registration) / 1024).toFixed(0)} KiB) for ${PACKAGE}`)
