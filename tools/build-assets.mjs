#!/usr/bin/env node
/**
 * Publish the artwork as content-hashed plugin asset references.
 *
 * The Client bundle must stay small, so sprites are not embedded: the Harness
 * asset route serves `<package>/assets/<path>` from the package itself, and the
 * generated manifest points at those URLs with a `?v=<content hash>` query that
 * busts the browser cache whenever a file changes.
 *
 * Reads `assets/<character>/<scene>.{webp,png}`, writes
 * `src/client/assets.generated.ts` (a few KiB of references, committed).
 * Run it through `npm run build` after changing anything under `assets/`.
 *
 * No dependencies; Node 20+.
 */
import { createHash } from 'node:crypto'
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, extname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const ASSETS = join(ROOT, 'assets')
const TARGET = join(ROOT, 'src', 'client', 'assets.generated.ts')
const PACKAGE = JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8')).name
const CHARACTERS = ['girl', 'whale']
const EXTENSIONS = ['webp', 'png']
/** The 15 scenes the Client renders; a missing pair is a runtime bug, not a smaller pack. */
const SCENES = [
  'idle', 'typing', 'thinking', 'planning', 'reading', 'searching',
  'working', 'success', 'waiting', 'error', 'tired', 'coffee',
  'sleeping', 'debugging', 'offline',
]
/** Interaction-only animations layered over a scene; additive, never a base state. */
const REACTIONS = [
  'error_cry', 'error_consoled', 'error_sniffle',
  'overwork_exhausted', 'overwork_cry', 'work_angry',
  'sleep_bothered', 'sleep_angry', 'typing_annoyed',
  'debugging_frustrated', 'idle_petted', 'idle_shy',
  'thinking_startled', 'waiting_pleading', 'success_cheered',
  'coffee_delighted', 'reading_disturbed', 'offline_worried',
]

/** First bytes of the SHA-1 digest of a file, used as a cache-busting revision. */
function revision(file) {
  return createHash('sha1').update(readFileSync(file)).digest('hex').slice(0, 8)
}

/** Scene stems present in one character directory, sorted. */
function sceneNames(directory) {
  return readdirSync(directory)
    .filter((file) => EXTENSIONS.includes(extname(file).slice(1).toLowerCase()))
    .map((file) => file.slice(0, -extname(file).length))
    .sort()
}

function main() {
  /** @type {Record<string, Record<string, Record<string, string>>>} */
  const manifest = {}
  const problems = []
  for (const character of CHARACTERS) {
    const directory = join(ASSETS, character)
    const scenes = {}
    for (const scene of sceneNames(directory)) {
      const entry = {}
      for (const extension of EXTENSIONS) {
        const file = join(directory, `${scene}.${extension}`)
        try {
          entry[extension] = `plugins/${PACKAGE}/assets/${character}/${scene}.${extension}?v=${revision(file)}`
        } catch {
          problems.push(`${character}/${scene}.${extension} is missing`)
        }
      }
      if (entry.webp === undefined || entry.png === undefined) continue
      scenes[scene] = entry
    }
    for (const scene of SCENES) {
      if (scenes[scene] === undefined) problems.push(`${character}/${scene} pair is incomplete or missing`)
    }
    for (const reaction of REACTIONS) {
      if (scenes[reaction] === undefined) problems.push(`${character}/${reaction} reaction pair is incomplete or missing`)
    }
    manifest[character] = scenes
  }
  if (problems.length > 0) {
    for (const problem of problems) console.error(`error: ${problem}`)
    process.exit(1)
  }
  const counts = Object.fromEntries(
    Object.entries(manifest).map(([character, scenes]) => [character, Object.keys(scenes).length]),
  )
  const source = [
    '/** Generated by tools/build-assets.mjs; plugin asset-route references with content-hash cache busting. */',
    `export const COMPANION_ASSETS: Record<string, Record<string, { webp: string; png: string }>> = ${JSON.stringify(manifest)}`,
    '',
  ].join('\n')
  writeFileSync(TARGET, source)
  console.log(`wrote ${TARGET.replace(ROOT + '/', '')} (${(Buffer.byteLength(source) / 1024).toFixed(1)} KiB, ${JSON.stringify(counts)})`)
}

main()
